-- =====================================================================
--  Potongan pajak rekanan per bulan
--
--  Laporan Partner mendapat kolom potongan pajak: persentase diisi
--  pengguna, nominal dihitung (bruto × persen, dibulatkan ke rupiah) —
--  nominal TIDAK disimpan (invarian 2: tidak ada angka turunan yang bisa
--  basi). Permintaan pengguna, 13 Oktober 2026.
--
--  Per rekanan PER BULAN, bukan kolom di pemilik: mengubah tarif bulan
--  ini tidak boleh mengubah potongan yang sudah dibayarkan bulan lalu.
--  Tanpa baris = tarif bawaan 0,5%, angka di lembar pengguna (KM SANEI /
--  TS 28) dan di Laporan per Kapal (20250126); aplikasi yang memakainya.
--  Laporan per Kapal membaca tarif yang sama, jadi kedua laporan tidak
--  pernah memotong pajak berbeda untuk rekanan dan bulan yang sama.
-- =====================================================================

create table pajak_partner (
  id          bigint generated by default as identity primary key,
  entity_id   uuid not null references entities(id) on delete restrict,
  pemilik_id  bigint not null,
  bulan       smallint not null check (bulan between 1 and 12),
  tahun       smallint not null,
  persen      numeric(5,2) not null check (persen between 0 and 100),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),

  unique (pemilik_id, bulan, tahun),
  -- Rekanan entitas lain tidak bisa dirujuk (keputusan Q-6, 20250110).
  constraint pajak_partner_pemilik_fkey foreign key (pemilik_id, entity_id)
    references pemilik (id, entity_id) on delete cascade
);

comment on table pajak_partner is
  'Persentase potongan pajak pembayaran rekanan per bulan. Tanpa baris = 0,5%. Nominal dihitung, tidak disimpan.';

create index pajak_partner_entity_periode_idx on pajak_partner (entity_id, tahun, bulan);

-- Perlakuan baku tabel operasional (loop 20250108), ditulis satu per satu
-- seperti lampiran_operasional (20250119).
create trigger pajak_partner_updated_at before update on pajak_partner
  for each row execute function set_updated_at();
create trigger audit_pajak_partner after insert or update or delete on pajak_partner
  for each row execute function audit_row();

alter table pajak_partner enable row level security;

create policy pajak_partner_select on pajak_partner for select to authenticated
  using (can_read_operational(entity_id));

create policy pajak_partner_write on pajak_partner for all to authenticated
  using (can_write_operational(entity_id))
  with check (can_write_operational(entity_id));

grant select, insert, update, delete on pajak_partner to authenticated;
