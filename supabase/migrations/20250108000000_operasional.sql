-- =====================================================================
--  BAGIAN 7 — PELAKU PERUBAHAN
--
--  created_by dan updated_by diisi database dari sesi, tidak dipercaya
--  dari klien — pola yang sama dengan guard_period_insert. Sesi tanpa
--  auth.uid() (skrip migrasi data) mempertahankan nilai yang dikirim.
-- =====================================================================

create or replace function stamp_operational_actor()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    new.created_by := coalesce(auth.uid(), new.created_by);
  else
    new.created_by := old.created_by;
  end if;
  new.updated_by := coalesce(auth.uid(), new.updated_by);
  return new;
end;
$$;

create trigger transaksi_operasional_actor before insert or update on transaksi_operasional
  for each row execute function stamp_operational_actor();
create trigger operasional_rekap_actor before insert or update on operasional_rekap
  for each row execute function stamp_operational_actor();


-- =====================================================================
--  BAGIAN 8 — TRIGGER BAKU, RLS, DAN GRANT
--
--  Setiap tabel operasional mendapat perlakuan yang persis sama, jadi
--  ditulis sekali dalam satu loop. Daftar tabelnya ada di satu tempat;
--  tabel operasional baru yang tidak ditambahkan ke daftar ini tidak
--  punya RLS — dan tests/operasional-rls.test.ts akan gagal.
--
--    updated_at  set_updated_at()
--    audit       audit_row()                         invarian 4
--    RLS         baca can_read_operational()         invarian 1
--                tulis can_write_operational()
--    grant       seluas policy-nya; 'anon' tidak mendapat apa pun
-- =====================================================================

do $$
declare
  t text;
begin
  foreach t in array array[
    'pemilik', 'kapal', 'karyawan', 'karyawan_catatan', 'kendaraan',
    'kapal_rute', 'kapal_muatan_detail', 'operasional_rekap',
    'transaksi_operasional', 'gaji_telly', 'paguyuban', 'pengeluaran',
    'pencairan', 'pencairan_approval', 'laporan_pendapatan', 'laporan_kumpulan'
  ]
  loop
    execute format(
      'create trigger %1$s_updated_at before update on %1$I
         for each row execute function set_updated_at()', t);

    execute format(
      'create trigger audit_%1$s after insert or update or delete on %1$I
         for each row execute function audit_row()', t);

    execute format('alter table %I enable row level security', t);

    execute format(
      'create policy %1$s_select on %1$I for select to authenticated
         using (can_read_operational(entity_id))', t);

    execute format(
      'create policy %1$s_write on %1$I for all to authenticated
         using (can_write_operational(entity_id))
         with check (can_write_operational(entity_id))', t);

    execute format(
      'grant select, insert, update, delete on %I to authenticated', t);
  end loop;
end;
$$;
