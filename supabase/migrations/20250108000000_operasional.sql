-- =====================================================================
--  MODUL OPERASIONAL — PLATFORM TERPADU
--
--  Sistem operasional ILJ (Laravel, repo LaporanKeuangan) pindah ke
--  database yang sama dengan portal laporan. Tabel di bawah adalah
--  bentuk AKHIR schema Laravel per 6 Oktober 2026 — hasil seluruh
--  45 migrasinya, bukan salinan migrasi per migrasi — diterjemahkan ke
--  Postgres dengan aturan portal ini.
--
--  Yang sengaja berbeda dari Laravel, dan alasannya:
--
--    - entity_id di SETIAP tabel. Keputusan 7 Oktober 2026: data
--      operasional milik entitas, dan akses mengikuti user_entity_access
--      seperti laporan. Seluruh data lama adalah ILJ.
--    - nominal uang numeric(18,2), bukan decimal(15,2). Invarian 3.
--    - id tetap bigint, bukan uuid, dan `generated by default` — skrip
--      migrasi data menyisipkan id lama apa adanya, sehingga nomor yang
--      sudah tercetak di dokumen tetap menunjuk baris yang sama.
--    - created_by/updated_by menunjuk profiles, bukan users. Akun Laravel
--      tidak dipindah (password bcrypt tidak bisa dibawa ke Neon Auth);
--      direksi membuat ulang akunnya.
--    - activity_logs TIDAK dibuat. Setiap tabel di sini diaudit trigger
--      audit_row() (invarian 4); notifikasi kolaborasi membaca audit_log.
--    - pengeluaran_line_mapping TIDAK dibuat. Sudah tidak dipakai sejak
--      keputusan 4 Oktober 2026; penggantinya operational_expense_mapping.
--    - users, sessions, cache, jobs TIDAK dibuat. Itu infrastruktur
--      Laravel, bukan data.
--
--  Yang sengaja SAMA, meski tidak ideal, supaya data lama masuk tanpa
--  diubah:
--
--    - transaksi_operasional.pendapatan dan kapal_muatan_detail.
--      pendapatan_rekanan menyimpan hasil hitung (tonase x tarif). Itu
--      bukan subtotal laporan laba rugi, jadi tidak melanggar invarian 2,
--      tetapi tetap angka turunan yang bisa basi. Ditinjau saat modulnya
--      di-port — lihat docs/PENGGABUNGAN.md.
--    - kolom `pendapatan` di transaksi_operasional adalah BEBAN rekanan,
--      bukan pendapatan. Namanya dipertahankan; lihat
--      docs/task/10-integrasi-operasional.md.
--    - laporan_pendapatan.tanggal_kegiatan tetap teks. Di Laravel kolom
--      itu string bebas ("12-15 Mei"), bukan tanggal.
-- =====================================================================


