-- --- 1a. Modul operasional --------------------------------------------
--
--  Baca: direksi dan admin_operasional, pada entitas yang boleh ia
--  lihat. Tulis: admin_operasional saja.
--
--  Direksi tidak menulis. Di Laravel, peran yang membaca tanpa menulis
--  adalah HRD, dan untuk saat ini akun HRD memakai peran direksi —
--  memberi direksi hak tulis akan memberikannya juga ke HRD tanpa ada
--  yang memutuskannya. Daftar izin, bukan daftar larangan: peran baru
--  tidak mendapat apa pun sampai dinyatakan di sini.

create or replace function can_read_operational(target_entity uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(current_user_role() in ('direksi', 'admin_operasional'), false)
     and has_entity_access(target_entity);
$$;

comment on function can_read_operational(uuid) is
  'Boleh membaca data operasional entitas ini: direksi dan admin_operasional.';

create or replace function can_write_operational(target_entity uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(current_user_role() = 'admin_operasional', false)
     and has_entity_access(target_entity);
$$;

comment on function can_write_operational(uuid) is
  'Boleh menulis data operasional entitas ini: admin_operasional yang ditugaskan.';


-- --- 1b. Laporan laba rugi: daftar izin eksplisit ---------------------
--
--  Sampai migrasi ini, periods_insert, periods_update, dan lines_write
--  hanya mensyaratkan "punya akses entitas dan bukan auditor". Itu benar
--  selama setiap peran non-auditor memang peran laporan. admin_operasional
--  bukan: tanpa perubahan ini, admin operasional yang ditugaskan ke ILJ
--  dapat membuat periode P&L ILJ, mengubah angkanya, dan MENGAJUKANNYA —
--  guard_period_transition tidak membatasi siapa yang boleh mengajukan.
--
--  Kedua fungsi mempertahankan hak keempat peran lama persis seperti
--  sebelumnya. Yang berubah hanya: peran yang tidak disebut tidak
--  mendapat apa pun.
--
--  Baca P&L juga dipersempit. Apakah admin operasional boleh membaca
--  laporan laba rugi belum diputuskan; sampai diputuskan, tidak.

create or replace function can_read_reports()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    current_user_role() in ('direksi', 'manajer_keuangan', 'staf_entitas', 'auditor'),
    false
  );
$$;

comment on function can_read_reports() is
  'Peran yang boleh membaca periode dan baris laporan laba rugi. Cakupan entitas tetap has_entity_access().';

create or replace function can_write_reports()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    current_user_role() in ('direksi', 'manajer_keuangan', 'staf_entitas'),
    false
  );
$$;

comment on function can_write_reports() is
  'Peran yang boleh membuat periode dan menulis baris laporan. Pengganti `not is_readonly_role()` di policy laporan.';

drop policy if exists periods_select on periods;
create policy periods_select on periods for select to authenticated
  using (has_entity_access(entity_id) and can_read_reports());

drop policy if exists periods_insert on periods;
create policy periods_insert on periods for insert to authenticated
  with check (has_entity_access(entity_id) and can_write_reports());

drop policy if exists periods_update on periods;
create policy periods_update on periods for update to authenticated
  using (has_entity_access(entity_id) and can_write_reports())
  with check (has_entity_access(entity_id) and can_write_reports());

drop policy if exists lines_select on report_lines;
create policy lines_select on report_lines for select to authenticated
  using (
    can_read_reports()
    and exists (
      select 1 from periods p
      where p.id = report_lines.period_id
        and has_entity_access(p.entity_id)
    )
  );

drop policy if exists lines_write on report_lines;
create policy lines_write on report_lines for all to authenticated
  using (
    can_write_reports()
    and exists (
      select 1 from periods p
      where p.id = report_lines.period_id
        and has_entity_access(p.entity_id)
        and p.status = 'draft'
    )
  )
  with check (
    can_write_reports()
    and exists (
      select 1 from periods p
      where p.id = report_lines.period_id
        and has_entity_access(p.entity_id)
        and p.status = 'draft'
    )
  );


