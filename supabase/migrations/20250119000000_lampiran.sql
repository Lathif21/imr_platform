-- =====================================================================
--  Lampiran: dokumen asli sebagai bukti (diputuskan 13 Oktober 2026).
--
--  Berkasnya di Neon Object Storage (bucket S3_BUCKET); tabel ini hanya
--  mencatat kunci objek, nama, tipe, dan ukuran. Dua tabel, karena hak
--  aksesnya berbeda:
--
--    lampiran_operasional  kegiatan kapal, invoice pendapatan, pencairan,
--                          pengeluaran — RLS operasional, seperti induknya.
--    lampiran_periode      Laporan P&L bulanan — RLS laporan. Boleh
--                          ditambah kapan saja (dokumen bertanda tangan
--                          sering datang setelah approval), tetapi hanya
--                          dihapus selama periodenya draft atau diajukan:
--                          bukti laporan yang sudah disetujui tidak hilang.
--
--  Composite FK (induk_id, entity_id) seperti 20250110: lampiran tidak bisa
--  menunjuk induk milik entitas lain. Tidak ada UPDATE dari aplikasi —
--  berkas diganti dengan hapus lalu unggah.
--
--  Menghapus induk ikut menghapus barisnya (cascade); objek di storage
--  tertinggal dan dibersihkan terpisah — penghapusan lampiran oleh
--  pengguna menghapus objeknya langsung.
-- =====================================================================

alter table laporan_pendapatan add constraint laporan_pendapatan_id_entity_key unique (id, entity_id);
alter table pengeluaran        add constraint pengeluaran_id_entity_key unique (id, entity_id);
alter table periods            add constraint periods_id_entity_key unique (id, entity_id);

create table lampiran_operasional (
  id                    bigint generated by default as identity primary key,
  entity_id             uuid not null references entities(id) on delete restrict,
  operasional_rekap_id  bigint,
  laporan_pendapatan_id bigint,
  pencairan_id          bigint,
  pengeluaran_id        bigint,
  nama_file             text not null check (length(btrim(nama_file)) between 1 and 255),
  tipe                  text not null,
  ukuran                bigint not null check (ukuran > 0),
  kunci                 text not null unique,
  diunggah_oleh         uuid default auth.uid(),
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),

  constraint lampiran_operasional_satu_induk check (
    num_nonnulls(operasional_rekap_id, laporan_pendapatan_id, pencairan_id, pengeluaran_id) = 1
  ),
  constraint lampiran_operasional_rekap_fkey foreign key (operasional_rekap_id, entity_id)
    references operasional_rekap (id, entity_id) on delete cascade,
  constraint lampiran_operasional_pendapatan_fkey foreign key (laporan_pendapatan_id, entity_id)
    references laporan_pendapatan (id, entity_id) on delete cascade,
  constraint lampiran_operasional_pencairan_fkey foreign key (pencairan_id, entity_id)
    references pencairan (id, entity_id) on delete cascade,
  constraint lampiran_operasional_pengeluaran_fkey foreign key (pengeluaran_id, entity_id)
    references pengeluaran (id, entity_id) on delete cascade
);

create index on lampiran_operasional (operasional_rekap_id) where operasional_rekap_id is not null;
create index on lampiran_operasional (laporan_pendapatan_id) where laporan_pendapatan_id is not null;
create index on lampiran_operasional (pencairan_id) where pencairan_id is not null;
create index on lampiran_operasional (pengeluaran_id) where pengeluaran_id is not null;

create trigger lampiran_operasional_updated_at before update on lampiran_operasional
  for each row execute function set_updated_at();
create trigger audit_lampiran_operasional after insert or update or delete on lampiran_operasional
  for each row execute function audit_row();

alter table lampiran_operasional enable row level security;

create policy lampiran_operasional_select on lampiran_operasional for select to authenticated
  using (can_read_operational(entity_id));

create policy lampiran_operasional_write on lampiran_operasional for all to authenticated
  using (can_write_operational(entity_id))
  with check (can_write_operational(entity_id));

grant select, insert, update, delete on lampiran_operasional to authenticated;


create table lampiran_periode (
  id            bigint generated by default as identity primary key,
  entity_id     uuid not null references entities(id) on delete restrict,
  period_id     uuid not null,
  nama_file     text not null check (length(btrim(nama_file)) between 1 and 255),
  tipe          text not null,
  ukuran        bigint not null check (ukuran > 0),
  kunci         text not null unique,
  diunggah_oleh uuid default auth.uid(),
  created_at    timestamptz not null default now(),

  constraint lampiran_periode_period_fkey foreign key (period_id, entity_id)
    references periods (id, entity_id) on delete restrict
);

create index on lampiran_periode (period_id);

create trigger audit_lampiran_periode after insert or update or delete on lampiran_periode
  for each row execute function audit_row();

alter table lampiran_periode enable row level security;

create policy lampiran_periode_select on lampiran_periode for select to authenticated
  using (has_entity_access(entity_id) and can_read_reports());

create policy lampiran_periode_insert on lampiran_periode for insert to authenticated
  with check (has_entity_access(entity_id) and can_write_reports());

create policy lampiran_periode_delete on lampiran_periode for delete to authenticated
  using (
    has_entity_access(entity_id)
    and can_write_reports()
    and exists (
      select 1 from periods p
       where p.id = lampiran_periode.period_id
         and p.status in ('draft', 'submitted')
    )
  );

grant select, insert, delete on lampiran_periode to authenticated;
